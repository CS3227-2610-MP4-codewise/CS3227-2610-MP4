import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Run from any directory. Only explicit --write updates generated catalogues.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const files = execFileSync(
  'git',
  [
    'ls-files',
    '--cached',
    '--others',
    '--exclude-standard',
    '--',
    'workflow',
    'logs',
  ],
  { cwd: root, encoding: 'utf8' },
)
  .trim()
  .split(/\r?\n/)
  .filter(Boolean);
const paths = [...new Set(files)]
  .filter((p) => existsSync(resolve(root, p)))
  .sort();
const link = (p, from) =>
  `[${p.slice(from.length)}](${p.slice(from.length).split('/').map(encodeURIComponent).join('/')})`;
const title = (p) => {
  const content = readFileSync(resolve(root, p), 'utf8');
  return (
    /^# (.+)$/m.exec(content)?.[1]?.replaceAll('|', '\\|') ??
    'Redacted interaction summary'
  );
};
function purpose(p) {
  if (p.includes('/evidence/')) {
    if (/\.(png|jpe?g|webp)$/i.test(p))
      return 'Historical synthetic UI capture; provenance is in the enclosing review.';
    if (/\.(json|csv|txt|log)$/i.test(p))
      return 'Recorded measurement, manifest or check output for the enclosing change.';
    if (extname(p) === '.md')
      return 'Dated verification, review, provenance or limitation record for the enclosing change.';
    return 'Reproduction harness or supporting artifact for the enclosing evidence record.';
  }
  if (/\.test\.[^/]+$|\/test_[^/]+\.py$/.test(p))
    return 'Automated regression/acceptance checks for this workflow module.';
  if (p.includes('/handoffs/'))
    return 'Producer/consumer transition: scope, source revisions, checks and next owner.';
  if (p.includes('/templates/'))
    return 'Reusable log, review or handoff template; not execution evidence.';
  if (p.includes('/agents/'))
    return 'Specialized agent role instructions and coordination boundaries.';
  if (p.endsWith('/README.md'))
    return 'Directory usage, commands, constraints and provenance.';
  if (p.includes('/scripts/'))
    return 'Development/release utility: ' + p.split('/').at(-1) + '.';
  if (p.includes('/experiment-tracker/'))
    return 'Opt-in experiment recording, reporting or coverage support.';
  if (p.includes('/ai-quality-evaluation/'))
    return 'Bounded opt-in provider evaluation/accounting support; inspect budget gates before execution.';
  if (p.includes('/measured-evaluation/'))
    return 'Synthetic context/validator experiment or review artifact.';
  if (p.includes('/fixtures/') || p.includes('/contracts/'))
    return 'Synthetic fixture or reusable shared-contract acceptance support.';
  if (/\/(auth|course|student)\//.test(p))
    return 'Local-only operator, synthetic integration fixture or verification helper for this slice.';
  if (p.includes('preview'))
    return 'Preview entry, adapter, configuration or verification support; not a second deployed service.';
  return (
    'Development coordination/reference document: ' + p.split('/').at(-1) + '.'
  );
}

const workflow =
  '# Workflow file inventory\n\nGenerated by `node workflow/scripts/submission-audit.mjs --write`. Includes tracked and non-ignored new files present at generation; historical artifacts retain their original meaning. Individual evidence files do not certify current release acceptance. Regenerate after final concurrent work lands.\n\n';
let inventory = workflow;
let group = '';
for (const p of paths.filter(
  (p) => p.startsWith('workflow/') && p !== 'workflow/FILE-INDEX.md',
)) {
  const next = p.split('/').length > 2 ? p.split('/')[1] : 'Root coordination';
  if (next !== group) {
    group = next;
    inventory += `\n## ${group}\n\n| File | Purpose |\n| --- | --- |\n`;
  }
  inventory += `| ${link(p, 'workflow/')} | ${purpose(p)} |\n`;
}
let logs =
  "# Interaction summary index\n\nGenerated from repository member summaries. These are AI-assisted, redacted records, not raw transcripts or proof that all historical prompts were captured. Members must verify their own entries. [Policy](README.md) defines Darryl's every-prompt format and Keith's substantial-request checkpoints. Missing usage, rationale, human review and historical gaps remain unavailable; do not reconstruct them as facts.\n\n";
for (const owner of ['darryl', 'keith']) {
  logs += `## ${owner === 'darryl' ? 'Darryl' : 'Keith'}\n\n| File | Recorded increment |\n| --- | --- |\n`;
  for (const p of paths.filter(
    (p) => p.startsWith(`logs/${owner}/`) && p.endsWith('.md'),
  )) {
    logs += `| ${link(p, 'logs/')} | ${title(p)} |\n`;
  }
  logs += '\n';
}
logs +=
  '## Submission verification\n\nThe submission audit checked available summaries against selected source/evidence records; it did not recover every chat or certify each historical entry. Both members must confirm coverage/correctness and reconcile available provisional telemetry before submission. See [release checklist](../workflow/evidence/final-submission/verification.md).\n';
if (process.argv.includes('--write')) {
  writeFileSync(resolve(root, 'workflow/FILE-INDEX.md'), inventory);
  writeFileSync(resolve(root, 'logs/INDEX.md'), logs);
  console.log('Updated workflow/FILE-INDEX.md and logs/INDEX.md');
}

const required = [
  'docs/UserGuide.md',
  'docs/DeveloperGuide.md',
  'docs/Reflections.md',
  'src/product-site/index.html',
  '.github/workflows/product-site.yml',
  'workflow/FILE-INDEX.md',
  'logs/INDEX.md',
];
const problems = [];
for (const p of required)
  if (
    !existsSync(resolve(root, p)) ||
    !readFileSync(resolve(root, p), 'utf8').trim()
  )
    problems.push(`Missing/empty deliverable: ${p}`);
const documents = [
  ...required.filter((p) => p.endsWith('.md')),
  'README.md',
  'workflow/evidence/final-submission/verification.md',
  'workflow/handoffs/final-submission.md',
];
for (const p of documents) {
  if (!existsSync(resolve(root, p))) {
    problems.push(`Missing document: ${p}`);
    continue;
  }
  const content = readFileSync(resolve(root, p), 'utf8');
  for (const match of content.matchAll(/\[[^\]\n]*\]\(([^)\n]+)\)/g)) {
    let target = match[1].replace(/^<|>$/g, '');
    if (/^(https?:|mailto:|#)/.test(target)) continue;
    target = decodeURIComponent(target.split('#')[0]);
    if (!existsSync(resolve(root, dirname(p), target)))
      problems.push(`Broken link in ${p}: ${target}`);
  }
}
const ug = readFileSync(resolve(root, 'docs/UserGuide.md'), 'utf8');
if ((ug.match(/Screenshot placeholder UG-/g) ?? []).length !== 12)
  problems.push('Expected 12 explicit User Guide screenshot placeholders');
if (/!\[[^\]]*\]\(/.test(ug))
  problems.push(
    'User Guide embeds an image despite placeholder-only instruction',
  );
const dg = readFileSync(resolve(root, 'docs/DeveloperGuide.md'), 'utf8');
if ((dg.match(/```mermaid/g) ?? []).length < 5)
  problems.push('Developer Guide diagram coverage missing');
const html = readFileSync(resolve(root, 'src/product-site/index.html'), 'utf8');
for (const [, href] of html.matchAll(/href="([^"]+)"/g)) {
  if (/^(https?:|#)/.test(href)) continue;
  if (!existsSync(resolve(root, 'src/product-site', href)))
    problems.push(`Missing site asset: ${href}`);
}
if (problems.length) {
  problems.forEach((p) => console.error(p));
  process.exitCode = 1;
} else
  console.log(
    'Submission files, documented local links, site assets, 12 placeholders and diagram presence: passed. Remote release/visual/manual acceptance is separate.',
  );
